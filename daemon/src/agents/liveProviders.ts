import {
  AgentResponse,
  AgentTaskPayload,
  FileDiff,
  IAgentAdapter,
} from '../types/contracts';

const SYSTEM_JSON_CONTRACT = `You are an autonomous coding agent inside Project MeGa X.
Respond ONLY with a valid JSON object matching this exact TypeScript schema:
{
  "taskId": "string",
  "explanation": "string",
  "fileDiffs": [
    {
      "path": "relative/path/to/file",
      "content": "full file content",
      "action": "CREATE" | "UPDATE" | "DELETE"
    }
  ],
  "microTasks": ["optional array of strings when planning"]
}`;

export interface BackoffOptions {
  maxRetries?: number;
  baseDelayMs?: number;
}

/**
 * Executes an async LLM API call with exponential backoff for transient rate-limit (429) or 5xx errors.
 */
export async function withExponentialBackoff<T>(
  operation: () => Promise<T>,
  options: BackoffOptions = {}
): Promise<T> {
  const maxRetries = options.maxRetries ?? 2;
  const baseDelayMs = options.baseDelayMs ?? 100;

  let lastError: unknown;
  for (let attempt = 0; attempt <= maxRetries; attempt++) {
    try {
      return await operation();
    } catch (err) {
      lastError = err;
      if (attempt === maxRetries) {
        break;
      }
      const delay = baseDelayMs * Math.pow(2, attempt);
      await new Promise((resolve) => setTimeout(resolve, delay));
    }
  }
  throw lastError;
}

/**
 * Extracts and parses a JSON AgentResponse from raw LLM text output (handling markdown code fences if present).
 */
export function parseAgentJsonResponse(
  taskId: string,
  rawText: string
): AgentResponse {
  const cleaned = rawText
    .trim()
    .replace(/^```(?:json)?\s*/i, '')
    .replace(/\s*```$/i, '')
    .trim();

  const parsed = JSON.parse(cleaned) as Partial<AgentResponse>;

  return {
    taskId: parsed.taskId ?? taskId,
    explanation: parsed.explanation ?? 'Generated by AI Agent',
    fileDiffs: Array.isArray(parsed.fileDiffs) ? parsed.fileDiffs : [],
    microTasks: Array.isArray(parsed.microTasks)
      ? parsed.microTasks
      : undefined,
  };
}

/**
 * Builds the user prompt string combining task instructions, context files, and self-healing stack traces.
 */
export function buildAgentUserPrompt(
  mode: 'PLAN' | 'EXECUTE' | 'REVIEW',
  payload: AgentTaskPayload,
  proposedDiffs?: FileDiff[]
): string {
  const sections: string[] = [
    `MODE: ${mode}`,
    `TASK_ID: ${payload.taskId}`,
    `PROMPT:\n${payload.prompt}`,
  ];

  if (payload.contextFiles && payload.contextFiles.length > 0) {
    const filesFormatted = payload.contextFiles
      .map((f) => `--- FILE: ${f.path} ---\n${f.content}`)
      .join('\n\n');
    sections.push(`CONTEXT_FILES:\n${filesFormatted}`);
  }

  if (payload.errorLog) {
    sections.push(
      `SELF_HEALING_ERROR_LOG (Fix the root cause of this failure):\n${payload.errorLog}`
    );
  }

  if (proposedDiffs && proposedDiffs.length > 0) {
    sections.push(
      `PROPOSED_DIFFS_FOR_REVIEW:\n${JSON.stringify(proposedDiffs, null, 2)}`
    );
  }

  return sections.join('\n\n');
}

/**
 * Live Anthropic Claude 3.7 Sonnet Adapter (uses ANTHROPIC_API_KEY when present, or dry-run fallback).
 */
export class ClaudeAgentAdapter implements IAgentAdapter {
  public readonly agentId: string;
  private readonly apiKey?: string;
  private readonly model: string;

  constructor(
    agentId = 'claude-3-7-sonnet',
    apiKey = process.env.ANTHROPIC_API_KEY,
    model = 'claude-3-7-sonnet-latest'
  ) {
    this.agentId = agentId;
    this.apiKey = apiKey;
    this.model = model;
  }

  private async callAnthropic(userPrompt: string): Promise<string> {
    if (!this.apiKey) {
      throw new Error('ANTHROPIC_API_KEY is not set');
    }

    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': this.apiKey,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: this.model,
        max_tokens: 4096,
        system: SYSTEM_JSON_CONTRACT,
        messages: [{ role: 'user', content: userPrompt }],
      }),
    });

    if (!res.ok) {
      const errText = await res.text();
      throw new Error(`Anthropic API error (${res.status}): ${errText}`);
    }

    const data = (await res.json()) as {
      content?: { type: string; text?: string }[];
    };
    return data.content?.[0]?.text ?? '{}';
  }

  public async plan(payload: AgentTaskPayload): Promise<AgentResponse> {
    if (!this.apiKey) {
      return {
        taskId: payload.taskId,
        explanation: `[${this.agentId}] Dry-run plan (set ANTHROPIC_API_KEY for live LLM calls).`,
        fileDiffs: [],
        microTasks: [payload.prompt],
      };
    }
    const raw = await this.callAnthropic(buildAgentUserPrompt('PLAN', payload));
    return parseAgentJsonResponse(payload.taskId, raw);
  }

  public async execute(payload: AgentTaskPayload): Promise<AgentResponse> {
    if (!this.apiKey) {
      return {
        taskId: payload.taskId,
        explanation: `[${this.agentId}] Dry-run execution (set ANTHROPIC_API_KEY for live LLM calls).`,
        fileDiffs: [],
      };
    }
    const raw = await this.callAnthropic(
      buildAgentUserPrompt('EXECUTE', payload)
    );
    return parseAgentJsonResponse(payload.taskId, raw);
  }
}

/**
 * Live OpenAI Codex / Reviewer Adapter (uses OPENAI_API_KEY when present, or dry-run fallback).
 */
export class CodexAgentAdapter implements IAgentAdapter {
  public readonly agentId: string;
  private readonly apiKey?: string;
  private readonly model: string;

  constructor(
    agentId = 'codex',
    apiKey = process.env.OPENAI_API_KEY,
    model = 'gpt-4o'
  ) {
    this.agentId = agentId;
    this.apiKey = apiKey;
    this.model = model;
  }

  private async callOpenAI(userPrompt: string): Promise<string> {
    if (!this.apiKey) {
      throw new Error('OPENAI_API_KEY is not set');
    }

    const res = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${this.apiKey}`,
      },
      body: JSON.stringify({
        model: this.model,
        response_format: { type: 'json_object' },
        messages: [
          { role: 'system', content: SYSTEM_JSON_CONTRACT },
          { role: 'user', content: userPrompt },
        ],
      }),
    });

    if (!res.ok) {
      const errText = await res.text();
      throw new Error(`OpenAI API error (${res.status}): ${errText}`);
    }

    const data = (await res.json()) as {
      choices?: { message?: { content?: string } }[];
    };
    return data.choices?.[0]?.message?.content ?? '{}';
  }

  public async plan(payload: AgentTaskPayload): Promise<AgentResponse> {
    if (!this.apiKey) {
      return {
        taskId: payload.taskId,
        explanation: `[${this.agentId}] Dry-run plan (set OPENAI_API_KEY for live LLM calls).`,
        fileDiffs: [],
        microTasks: [payload.prompt],
      };
    }
    const raw = await this.callOpenAI(buildAgentUserPrompt('PLAN', payload));
    return parseAgentJsonResponse(payload.taskId, raw);
  }

  public async execute(payload: AgentTaskPayload): Promise<AgentResponse> {
    if (!this.apiKey) {
      return {
        taskId: payload.taskId,
        explanation: `[${this.agentId}] Dry-run execution (set OPENAI_API_KEY for live LLM calls).`,
        fileDiffs: [],
      };
    }
    const raw = await this.callOpenAI(buildAgentUserPrompt('EXECUTE', payload));
    return parseAgentJsonResponse(payload.taskId, raw);
  }

  public async review(
    payload: AgentTaskPayload,
    proposedDiffs: FileDiff[]
  ): Promise<{ approved: boolean; feedback?: string }> {
    if (!this.apiKey) {
      return {
        approved: true,
        feedback: `[${this.agentId}] Dry-run review approved (${proposedDiffs.length} diffs).`,
      };
    }
    const raw = await this.callOpenAI(
      buildAgentUserPrompt('REVIEW', payload, proposedDiffs)
    );
    const parsed = JSON.parse(raw) as {
      approved?: boolean;
      explanation?: string;
      feedback?: string;
    };
    return {
      approved: parsed.approved ?? true,
      feedback: parsed.feedback ?? parsed.explanation ?? 'Reviewed by Codex',
    };
  }
}

/**
 * Live Gemini / AntiGravity Executor Adapter (uses GEMINI_API_KEY when present, or dry-run fallback).
 */
export class AntiGravityAgentAdapter implements IAgentAdapter {
  public readonly agentId: string;
  private readonly apiKey?: string;
  private readonly model: string;

  constructor(
    agentId = 'antigravity',
    apiKey = process.env.GEMINI_API_KEY,
    model = 'gemini-2.5-pro'
  ) {
    this.agentId = agentId;
    this.apiKey = apiKey;
    this.model = model;
  }

  private async callGemini(userPrompt: string): Promise<string> {
    if (!this.apiKey) {
      throw new Error('GEMINI_API_KEY is not set');
    }

    const url = `https://generativelanguage.googleapis.com/v1beta/models/${this.model}:generateContent?key=${this.apiKey}`;
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: SYSTEM_JSON_CONTRACT }] },
        contents: [{ role: 'user', parts: [{ text: userPrompt }] }],
        generationConfig: { responseMimeType: 'application/json' },
      }),
    });

    if (!res.ok) {
      const errText = await res.text();
      throw new Error(`Gemini API error (${res.status}): ${errText}`);
    }

    const data = (await res.json()) as {
      candidates?: { content?: { parts?: { text?: string }[] } }[];
    };
    return data.candidates?.[0]?.content?.parts?.[0]?.text ?? '{}';
  }

  public async plan(payload: AgentTaskPayload): Promise<AgentResponse> {
    if (!this.apiKey) {
      return {
        taskId: payload.taskId,
        explanation: `[${this.agentId}] Dry-run plan (set GEMINI_API_KEY for live LLM calls).`,
        fileDiffs: [],
        microTasks: [payload.prompt],
      };
    }
    const raw = await this.callGemini(buildAgentUserPrompt('PLAN', payload));
    return parseAgentJsonResponse(payload.taskId, raw);
  }

  public async execute(payload: AgentTaskPayload): Promise<AgentResponse> {
    if (!this.apiKey) {
      return {
        taskId: payload.taskId,
        explanation: `[${this.agentId}] Dry-run execution (set GEMINI_API_KEY for live LLM calls).`,
        fileDiffs: [],
      };
    }
    const raw = await this.callGemini(buildAgentUserPrompt('EXECUTE', payload));
    return parseAgentJsonResponse(payload.taskId, raw);
  }
}

